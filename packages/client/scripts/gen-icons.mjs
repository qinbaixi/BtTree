/* global console */
// Writes src/lib/faIcons.generated.ts: the Font Awesome 6 Free solid icon names.
// Names come from the installed package: metadata/icons.yml lists the styles of every icon, and
// css/all.css has a `.fa-<name> { --fa: ... }` rule for every glyph. Run with `npm run gen:icons -w @owlbt/client`.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const packageDir = dirname(require.resolve('@fortawesome/fontawesome-free/package.json'));
const metadata = readFileSync(join(packageDir, 'metadata', 'icons.yml'), 'utf8');
const css = readFileSync(join(packageDir, 'css', 'all.css'), 'utf8');

/** Names of icons whose `styles` list contains solid. */
function solidIconNames(yaml) {
  const names = new Set();
  let current;
  let inStyles = false;
  for (const line of yaml.split(/\r?\n/)) {
    const top = /^'?([a-z0-9-]+)'?:\s*$/.exec(line);
    if (top) {
      current = top[1];
      inStyles = false;
      continue;
    }
    if (/^ {2}styles:\s*$/.test(line)) {
      inStyles = true;
      continue;
    }
    const style = /^ {4}- ([a-z]+)\s*$/.exec(line);
    if (inStyles && style) {
      if (style[1] === 'solid' && current) {
        names.add(current);
      }
      continue;
    }
    if (/^ {2}\S/.test(line)) {
      inStyles = false;
    }
  }
  return names;
}

/** Names of icons that have a glyph rule in the stylesheet. */
function cssIconNames(stylesheet) {
  const names = new Set();
  for (const match of stylesheet.matchAll(/^\.fa-([a-z0-9-]+)\s*\{\s*--fa:/gm)) {
    names.add(match[1]);
  }
  return names;
}

const solid = solidIconNames(metadata);
const glyphs = cssIconNames(css);
const icons = [...solid].filter((name) => glyphs.has(name)).sort();
if (icons.length < 1000) {
  throw new Error(`Unexpected icon count ${icons.length}; check the Font Awesome files`);
}

const target = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'lib',
  'faIcons.generated.ts',
);
const body = [
  '// Generated by scripts/gen-icons.mjs from @fortawesome/fontawesome-free. Do not edit by hand.',
  '',
  'export const FA_SOLID_ICONS: readonly string[] = [',
  ...icons.map((name) => `  '${name}',`),
  '];',
  '',
].join('\n');
writeFileSync(target, body, 'utf8');
console.log(`Wrote ${icons.length} solid icons to ${target}`);
