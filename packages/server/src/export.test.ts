import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { HttpError } from './errors';
import { exportProject, exportTree, parseExportFormats } from './export';

const PROJECT = {
  nodes: [
    { name: 'Selector', isComposite: true },
    {
      name: 'Wait',
      export: { subType: 'wait' },
      properties: [{ name: 'duration', type: 'number', default: 100 }],
    },
  ],
};

const GOOD_TREE = { type: 'Selector', label: 'Root', childNodes: [{ type: 'Wait' }] };

describe('parseExportFormats', () => {
  it('accepts a non-empty list of known formats and removes duplicates', () => {
    expect(parseExportFormats(['lua'])).toEqual(['lua']);
    expect(parseExportFormats(['erlang', 'lua', 'erlang'])).toEqual(['erlang', 'lua']);
    expect(parseExportFormats(['ts', 'cs', 'lua'])).toEqual(['ts', 'cs', 'lua']);
  });

  it('rejects anything else with 400', () => {
    for (const bad of [undefined, 'lua', [], ['python'], [42]]) {
      expect(() => parseExportFormats(bad)).toThrow(HttpError);
    }
    expect(() => parseExportFormats(['python'])).toThrow('Unknown export format: python');
    expect(() => parseExportFormats([])).toThrow('formats must be a non-empty array');
  });
});

describe('exportTree and exportProject', () => {
  let root: string;

  const writeTree = (relPath: string, content: unknown) => {
    const path = join(root, relPath);
    mkdirSync(join(path, '..'), { recursive: true });
    writeFileSync(path, typeof content === 'string' ? content : JSON.stringify(content));
    return path;
  };

  beforeEach(() => {
    root = mkdtempSync(join(tmpdir(), 'owlbt-export-'));
    writeFileSync(join(root, 'owl-bt.json'), JSON.stringify(PROJECT));
  });

  afterEach(() => {
    rmSync(root, { recursive: true, force: true });
  });

  it('writes Erlang and Lua files to the default folders', async () => {
    const treePath = writeTree('trees/bt_mon_1000.json', GOOD_TREE);
    const result = await exportTree(treePath, ['erlang', 'lua']);

    expect(result.error).toBeUndefined();
    expect(result.warnings).toEqual([]);
    expect(result.files).toEqual([
      { format: 'erlang', path: join(root, 'export', 'erlang', 'bt_mon_1000.erl') },
      { format: 'lua', path: join(root, 'export', 'lua', 'bt_mon_1000.lua') },
    ]);

    const erl = readFileSync(result.files[0].path, 'utf8');
    expect(erl).toContain('-module(bt_mon_1000).');
    expect(erl).toContain('%% @Generated by owl-bt from trees/bt_mon_1000.json. Do not edit.');
    expect(erl).toContain('get_node(2) ->');
    expect(erl).toContain('        sub_type => wait,');

    const lua = readFileSync(result.files[1].path, 'utf8');
    expect(lua).toContain('-- Generated by owl-bt from trees/bt_mon_1000.json. Do not edit.');
    expect(lua).toContain('        sub_type = "wait",');
  });

  it('uses the project export settings for folder and file name, and the --out override', async () => {
    writeFileSync(
      join(root, 'owl-bt.json'),
      JSON.stringify({
        ...PROJECT,
        export: {
          erlang: { outDir: 'gen/erl', fileName: 'mon_{name}' },
          lua: { fileName: '{name}.lua' },
        },
      }),
    );
    const treePath = writeTree('trees/a.json', GOOD_TREE);

    const configured = await exportTree(treePath, ['erlang', 'lua']);
    expect(configured.files.map((f) => f.path)).toEqual([
      join(root, 'gen', 'erl', 'mon_a.erl'),
      join(root, 'export', 'lua', 'a.lua'),
    ]);
    expect(existsSync(join(root, 'gen', 'erl', 'mon_a.erl'))).toBe(true);
    expect(readFileSync(configured.files[0].path, 'utf8')).toContain('-module(mon_a).');

    const overridden = join(root, 'override');
    const forced = await exportTree(treePath, ['lua'], { outDir: overridden });
    expect(forced.files).toEqual([{ format: 'lua', path: join(overridden, 'a.lua') }]);
  });

  it('writes TypeScript and C# files to the default folders', async () => {
    const treePath = writeTree('trees/bt_mon_1000.json', GOOD_TREE);
    const result = await exportTree(treePath, ['ts', 'cs']);

    expect(result.error).toBeUndefined();
    expect(result.warnings).toEqual([]);
    expect(result.files).toEqual([
      { format: 'ts', path: join(root, 'export', 'ts', 'bt_mon_1000.ts') },
      { format: 'cs', path: join(root, 'export', 'cs', 'bt_mon_1000.cs') },
    ]);

    const ts = readFileSync(result.files[0].path, 'utf8');
    expect(
      ts.startsWith('// Generated by owl-bt from trees/bt_mon_1000.json. Do not edit.\n'),
    ).toBe(true);
    expect(ts).toContain('export const rootId = 1;');
    expect(ts).toContain("  2: {\n    node_id: 2,\n    type: 'task',\n    sub_type: 'wait',");

    const cs = readFileSync(result.files[1].path, 'utf8');
    expect(cs).toContain('namespace BehaviorTrees\n{\n    public static class BtMon1000\n');
    expect(cs).toContain('                ["sub_type"] = "wait",');
  });

  it('uses the configured C# namespace and warns when it is invalid', async () => {
    writeFileSync(
      join(root, 'owl-bt.json'),
      JSON.stringify({
        ...PROJECT,
        export: { cs: { namespace: 'Game.Ai', fileName: 'mon_{name}' } },
      }),
    );
    const treePath = writeTree('trees/a.json', GOOD_TREE);

    const configured = await exportTree(treePath, ['cs']);
    expect(configured.warnings).toEqual([]);
    expect(configured.files.map((f) => f.path)).toEqual([join(root, 'export', 'cs', 'mon_a.cs')]);
    expect(readFileSync(configured.files[0].path, 'utf8')).toContain(
      'namespace Game.Ai\n{\n    public static class MonA\n',
    );

    writeFileSync(
      join(root, 'owl-bt.json'),
      JSON.stringify({ ...PROJECT, export: { cs: { namespace: '1Game' } } }),
    );
    const invalid = await exportTree(treePath, ['cs']);
    expect(invalid.warnings).toEqual(['Invalid C# namespace "1Game", using BehaviorTrees']);
    expect(invalid.error).toBeUndefined();
    expect(readFileSync(invalid.files[0].path, 'utf8')).toContain('namespace BehaviorTrees\n{\n');

    const noCs = await exportTree(treePath, ['ts']);
    expect(noCs.warnings).toEqual([]);
  });

  it('sanitizes the Erlang module name from the file name', async () => {
    const treePath = writeTree('trees/My-Tree 2.json', GOOD_TREE);
    const result = await exportTree(treePath, ['erlang']);
    expect(readFileSync(result.files[0].path, 'utf8')).toContain('-module(my_tree_2).');
    expect(result.files[0].path.endsWith('My-Tree 2.erl')).toBe(true);
  });

  it('returns warnings for invalid property values and still writes the files', async () => {
    const treePath = writeTree('trees/w.json', {
      type: 'Selector',
      childNodes: [{ type: 'Wait', properties: [{ name: 'duration', value: 'soon' }] }],
    });
    const result = await exportTree(treePath, ['lua']);
    expect(result.warnings).toEqual(["root.childNodes[0]: invalid value for property 'duration'"]);
    expect(result.files).toHaveLength(1);
    expect(result.error).toBeUndefined();
  });

  it('reports a missing item type as an error and writes nothing', async () => {
    const treePath = writeTree('trees/bad.json', {
      type: 'Selector',
      childNodes: [{ type: 'Nope' }],
    });
    const result = await exportTree(treePath, ['erlang', 'lua']);
    expect(result.error).toBe("Missing node type 'Nope' at root.childNodes[0]");
    expect(result.files).toEqual([]);
    expect(existsSync(join(root, 'export'))).toBe(false);
  });

  it('reports invalid JSON as an error', async () => {
    const treePath = writeTree('trees/broken.json', '{ nope');
    const result = await exportTree(treePath, ['lua']);
    expect(result.error).toMatch(/^Invalid tree file:/);
  });

  it('throws 404 when the tree file or the project is missing', async () => {
    await expect(exportTree(join(root, 'trees', 'none.json'), ['lua'])).rejects.toMatchObject({
      status: 404,
      message: 'Path not found',
    });

    const outside = mkdtempSync(join(tmpdir(), 'owlbt-noproject-'));
    try {
      await expect(exportTree(join(outside, 'x.json'), ['lua'])).rejects.toMatchObject({
        status: 404,
        message: 'No project found',
      });
    } finally {
      rmSync(outside, { recursive: true, force: true });
    }
  });

  it('exports every tree of the project and keeps going after a failing tree', async () => {
    writeTree('trees/a.json', GOOD_TREE);
    writeTree('trees/b.json', { type: 'Selector', childNodes: [{ type: 'Nope' }] });
    writeTree('trees/sub/c.json', GOOD_TREE);
    writeTree('notes.txt.json', { unrelated: true });

    const batch = await exportProject(join(root, 'trees'), ['lua']);

    expect(batch.projectDir).toBe(root);
    expect(batch.truncated).toBe(false);
    expect(batch.results.map((r) => [r.relPath, r.error === undefined])).toEqual([
      ['trees/a.json', true],
      ['trees/b.json', false],
      ['trees/sub/c.json', true],
    ]);
    expect(batch.results[1].error).toContain("Missing node type 'Nope'");
    expect(existsSync(join(root, 'export', 'lua', 'a.lua'))).toBe(true);
    expect(existsSync(join(root, 'export', 'lua', 'c.lua'))).toBe(true);
  });

  it('throws 404 for a folder outside any project', async () => {
    const outside = mkdtempSync(join(tmpdir(), 'owlbt-noproject-'));
    try {
      await expect(exportProject(outside, ['lua'])).rejects.toMatchObject({ status: 404 });
    } finally {
      rmSync(outside, { recursive: true, force: true });
    }
  });
});
