import { describe, expect, it } from 'vitest';
import { toCSharp } from './csharp';
import { atom, type ExportModel, type ExportValue } from './model';

const OPTIONS = { sourcePath: 'trees/x.json', className: 'BtX', namespace: 'BehaviorTrees' };

function modelWith(fields: Array<[string, ExportValue]>, comment = 'Thing'): ExportModel {
  return {
    rootId: 1,
    entries: [{ id: 1, kind: 'node', comment, fields: [['node_id', 1], ...fields] }],
    warnings: [],
  };
}

function render(fields: Array<[string, ExportValue]>, comment?: string): string {
  return toCSharp(modelWith(fields, comment), OPTIONS);
}

/** The line `["key"] = <value>,` of the single test entry. */
function fieldLine(fields: Array<[string, ExportValue]>): string {
  const cs = render(fields);
  const line = cs.split('\n').find((text) => text.startsWith('                ["a"] = '));
  if (line === undefined) {
    throw new Error('field line not found');
  }
  return line.trim();
}

describe('toCSharp', () => {
  it('writes the header, namespace, class, RootId, Nodes and GetNode', () => {
    expect(toCSharp(modelWith([]), OPTIONS)).toBe(
      [
        '// <auto-generated>',
        '// Generated by owl-bt from trees/x.json. Do not edit.',
        '// </auto-generated>',
        'using System.Collections.Generic;',
        '',
        'namespace BehaviorTrees',
        '{',
        '    public static class BtX',
        '    {',
        '        public const int RootId = 1;',
        '',
        '        public static readonly Dictionary<int, Dictionary<string, object>> Nodes = new Dictionary<int, Dictionary<string, object>>',
        '        {',
        '            // Thing',
        '            [1] = new Dictionary<string, object>',
        '            {',
        '                ["node_id"] = 1,',
        '            },',
        '        };',
        '',
        '        public static Dictionary<string, object> GetNode(int id)',
        '        {',
        '            Dictionary<string, object> node;',
        '            return Nodes.TryGetValue(id, out node) ? node : null;',
        '        }',
        '    }',
        '}',
        '',
      ].join('\n'),
    );
  });

  it('uses the given namespace and class name', () => {
    const cs = toCSharp(modelWith([]), { ...OPTIONS, className: 'Mon', namespace: 'Game.Ai' });
    expect(cs).toContain('namespace Game.Ai\n{\n    public static class Mon\n');
  });

  it('writes int literals for int32 values and long literals beyond', () => {
    expect(fieldLine([['a', 2147483647]])).toBe('["a"] = 2147483647,');
    expect(fieldLine([['a', -2147483648]])).toBe('["a"] = -2147483648,');
    expect(fieldLine([['a', 2147483648]])).toBe('["a"] = 2147483648L,');
    expect(fieldLine([['a', 2 ** 62]])).toBe('["a"] = 4611686018427387904L,');
  });

  it('writes other numbers as doubles with a decimal point or exponent', () => {
    expect(fieldLine([['a', 0.5]])).toBe('["a"] = 0.5,');
    expect(fieldLine([['a', -2.25]])).toBe('["a"] = -2.25,');
    expect(fieldLine([['a', 1.5e21]])).toBe('["a"] = 1.5E+21,');
    expect(fieldLine([['a', 1e-7]])).toBe('["a"] = 1E-7,');
    expect(fieldLine([['a', 2 ** 63]])).toBe('["a"] = 9223372036854776000.0,');
    expect(fieldLine([['a', Infinity]])).toBe('["a"] = double.PositiveInfinity,');
  });

  it('writes booleans and null as literals', () => {
    expect(fieldLine([['a', true]])).toBe('["a"] = true,');
    expect(fieldLine([['a', false]])).toBe('["a"] = false,');
    expect(fieldLine([['a', null]])).toBe('["a"] = null,');
  });

  it('writes strings and atoms as escaped string literals', () => {
    expect(fieldLine([['a', atom('selector')]])).toBe('["a"] = "selector",');
    expect(fieldLine([['a', 'say "hi" \\ ok']])).toBe('["a"] = "say \\"hi\\" \\\\ ok",');
    expect(fieldLine([['a', 'a\nb\rc\td\u0001']])).toBe('["a"] = "a\\nb\\rc\\td\\u0001",');
  });

  it('writes id lists as int arrays, other arrays as object arrays', () => {
    const cs = render([
      ['children', [3, 5]],
      ['mixed', [1, 'x', atom('y'), null]],
      ['empty', []],
    ]);
    expect(cs).toContain('                ["children"] = new int[] { 3, 5 },\n');
    expect(cs).toContain('                ["mixed"] = new object[] { 1, "x", "y", null },\n');
    expect(cs).toContain('                ["empty"] = new object[] { },\n');
  });

  it('writes an empty id list with the same spacing as the reference output', () => {
    expect(render([['decorators', []]])).toContain('["decorators"] = new int[] { },');
  });

  it('writes a non-empty top-level map one key per line', () => {
    const cs = render([
      [
        'properties',
        {
          map: [
            ['sight_dist', 5000],
            ['trace_dist', 'x'],
          ],
        },
      ],
    ]);
    expect(cs).toContain(
      [
        '                ["properties"] = new Dictionary<string, object>',
        '                {',
        '                    ["sight_dist"] = 5000,',
        '                    ["trace_dist"] = "x",',
        '                },',
      ].join('\n'),
    );
  });

  it('writes an empty top-level map as a new dictionary', () => {
    expect(render([['properties', { map: [] }]])).toContain(
      '["properties"] = new Dictionary<string, object>(),',
    );
  });

  it('writes nested maps inline with trailing commas, quoting every key', () => {
    expect(
      fieldLine([
        [
          'a',
          [
            {
              map: [
                ['k', 1],
                ['end', false],
                ['with "quote"', null],
              ],
            },
          ],
        ],
      ]),
    ).toBe(
      '["a"] = new object[] { new Dictionary<string, object> { ["k"] = 1, ["end"] = false, ["with \\"quote\\""] = null, } },',
    );
    expect(fieldLine([['a', [{ map: [] }]]])).toBe(
      '["a"] = new object[] { new Dictionary<string, object>() },',
    );
  });

  it('writes one comment line per entry and keeps line breaks out of it', () => {
    const cs = render([], 'Selector - Root\r\nNext line');
    expect(cs).toContain('            // Selector - Root Next line\n            [1] = ');
  });
});
