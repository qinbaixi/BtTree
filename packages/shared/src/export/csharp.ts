import {
  cachedFormatter,
  isExportAtom,
  isExportMap,
  type ExportEntry,
  type ExportMap,
  type ExportModel,
  type ExportValue,
} from './model';
import { csharpString } from './names';

/** Keys repeat for every entry; atoms are type and enum names. */
const csharpName = cachedFormatter(csharpString);

export interface CSharpOptions {
  /** Tree file path relative to the project directory, forward slashes. */
  sourcePath: string;
  /** C# class name: a valid identifier (see csharpClassName). */
  className: string;
  /** C# namespace: dotted identifiers (validated with parseCsNamespace). */
  namespace: string;
}

/** Top-level entry fields that hold lists of ids. */
const ID_LIST_FIELDS: ReadonlySet<string> = new Set(['decorators', 'services', 'children']);

const INT32_MIN = -(2 ** 31);
const INT32_MAX = 2 ** 31 - 1;
const INT64_MIN = -(2 ** 63);
const INT64_LIMIT = 2 ** 63;

/** Line terminators in comments: CR, LF, NEL, U+2028 and U+2029. */
const LINE_BREAKS = new RegExp('[\\r\\n\\u0085\\u2028\\u2029]+', 'g');

/** Indents used by the generator, built once. */
const PADS: string[] = [];

function pad(indent: number): string {
  return (PADS[indent] ??= ' '.repeat(indent));
}

/**
 * C# literal for a number: int for int32 integers, long (`L` suffix) for other integers in the
 * int64 range, otherwise a double with a decimal point or exponent (`0.5`, `1.5E+21`).
 */
function csharpNumber(n: number): string {
  if (Number.isInteger(n) && n >= INT32_MIN && n <= INT32_MAX) {
    return String(n);
  }
  if (Number.isInteger(n) && n >= INT64_MIN && n < INT64_LIMIT) {
    return `${BigInt(n).toString()}L`;
  }
  if (Number.isNaN(n)) {
    return 'double.NaN';
  }
  if (n === Infinity) {
    return 'double.PositiveInfinity';
  }
  if (n === -Infinity) {
    return 'double.NegativeInfinity';
  }
  const text = String(n).replace('e', 'E');
  return /[.E]/.test(text) ? text : `${text}.0`;
}

/** Single-line C# expression for an `object` slot. */
function inline(value: ExportValue): string {
  if (value === null) {
    return 'null';
  }
  if (typeof value === 'boolean') {
    return value ? 'true' : 'false';
  }
  if (typeof value === 'number') {
    return csharpNumber(value);
  }
  if (typeof value === 'string') {
    return csharpString(value);
  }
  if (Array.isArray(value)) {
    return arrayLiteral(
      'object',
      value.map((item) => inline(item)),
    );
  }
  if (isExportAtom(value)) {
    return csharpName(value.atom);
  }
  return dictionaryInline(value);
}

/** `new <type>[] { a, b }`; an empty array keeps the `{ }` spacing. */
function arrayLiteral(type: string, items: string[]): string {
  return items.length === 0 ? `new ${type}[] { }` : `new ${type}[] { ${items.join(', ')} }`;
}

function dictionaryInline(map: ExportMap): string {
  if (map.map.length === 0) {
    return 'new Dictionary<string, object>()';
  }
  const pairs = map.map.map(([key, inner]) => `[${csharpName(key)}] = ${inline(inner)},`);
  return `new Dictionary<string, object> { ${pairs.join(' ')} }`;
}

/**
 * Lines of one top-level entry field. Id lists become `int[]`, other arrays `object[]`, and
 * non-empty maps are written one key per line.
 */
function pushFieldLines(lines: string[], key: string, value: ExportValue, indent: number): void {
  const head = `${pad(indent)}[${csharpName(key)}] = `;
  if (Array.isArray(value) && ID_LIST_FIELDS.has(key)) {
    lines.push(
      `${head}${arrayLiteral(
        'int',
        value.map((item) => inline(item)),
      )},`,
    );
    return;
  }
  if (isExportMap(value) && value.map.length > 0) {
    lines.push(`${head}new Dictionary<string, object>`, `${pad(indent)}{`);
    for (const [innerKey, inner] of value.map) {
      lines.push(`${pad(indent + 4)}[${csharpName(innerKey)}] = ${inline(inner)},`);
    }
    lines.push(`${pad(indent)}},`);
    return;
  }
  lines.push(`${head}${inline(value)},`);
}

function pushEntryLines(lines: string[], entry: ExportEntry): void {
  const indent = 12;
  const comment = entry.comment.replace(LINE_BREAKS, ' ');
  lines.push(
    `${pad(indent)}// ${comment}`,
    `${pad(indent)}[${entry.id}] = new Dictionary<string, object>`,
    `${pad(indent)}{`,
  );
  for (const [key, value] of entry.fields) {
    pushFieldLines(lines, key, value, indent + 4);
  }
  lines.push(`${pad(indent)}},`);
}

/**
 * Renders the export model as a static C# class (C# 7.3 compatible) with RootId, Nodes and GetNode(id).
 * Every node is a Dictionary<string, object>; id lists are int arrays.
 */
export function toCSharp(model: ExportModel, options: CSharpOptions): string {
  const lines: string[] = [
    '// <auto-generated>',
    `// Generated by owl-bt from ${options.sourcePath}. Do not edit.`,
    '// </auto-generated>',
    'using System.Collections.Generic;',
    '',
    `namespace ${options.namespace}`,
    '{',
    `${pad(4)}public static class ${options.className}`,
    `${pad(4)}{`,
    `${pad(8)}public const int RootId = ${model.rootId};`,
    '',
    `${pad(8)}public static readonly Dictionary<int, Dictionary<string, object>> Nodes = new Dictionary<int, Dictionary<string, object>>`,
    `${pad(8)}{`,
  ];
  for (const entry of model.entries) {
    pushEntryLines(lines, entry);
  }
  lines.push(
    `${pad(8)}};`,
    '',
    `${pad(8)}public static Dictionary<string, object> GetNode(int id)`,
    `${pad(8)}{`,
    `${pad(12)}Dictionary<string, object> node;`,
    `${pad(12)}return Nodes.TryGetValue(id, out node) ? node : null;`,
    `${pad(8)}}`,
    `${pad(4)}}`,
    '}',
    '',
  );
  return lines.join('\n');
}
