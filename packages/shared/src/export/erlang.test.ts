import { describe, expect, it } from 'vitest';
import { atom, type ExportModel, type ExportValue } from './model';
import { toErlang } from './erlang';

function modelWith(fields: Array<[string, ExportValue]>, comment = 'Thing'): ExportModel {
  return {
    rootId: 1,
    entries: [{ id: 1, kind: 'node', comment, fields: [['node_id', 1], ...fields] }],
    warnings: [],
  };
}

function render(fields: Array<[string, ExportValue]>, comment?: string): string {
  const erl = toErlang(modelWith(fields, comment), { module: 'm', sourcePath: 'trees/m.json' });
  return erl.slice(erl.indexOf('get_node(1) ->'), erl.indexOf('get_node(_)'));
}

describe('toErlang', () => {
  it('writes the header, export list and the root accessor', () => {
    const erl = toErlang(modelWith([]), { module: 'bt_a', sourcePath: 'trees/a/b.json' });
    expect(erl.split('\n').slice(0, 9)).toEqual([
      '%% -*- coding: utf-8 -*-',
      `%%${'-'.repeat(78)}`,
      '%% @File   : bt_a',
      '%% @Generated by owl-bt from trees/a/b.json. Do not edit.',
      `%%${'-'.repeat(78)}`,
      '-module(bt_a).',
      '-export([',
      '    get_node/1,',
      '    get_root_node/0',
    ]);
    expect(erl.endsWith('get_node(_) -> undefined.\n\n\nget_root_node() -> 1.\n\n\n')).toBe(true);
  });

  it('writes a comment line before every clause', () => {
    const model: ExportModel = {
      rootId: 1,
      entries: [
        { id: 1, kind: 'node', comment: 'Selector - Root', fields: [['node_id', 1]] },
        { id: 2, kind: 'decorator', comment: 'Inv', fields: [['node_id', 2]] },
      ],
      warnings: [],
    };
    const erl = toErlang(model, { module: 'm', sourcePath: 's' });
    expect(erl).toContain(
      '%% Selector - Root\nget_node(1) ->\n    #{\n        node_id => 1\n    };\n%% Inv\nget_node(2) ->',
    );
  });

  it('writes atoms, numbers, booleans and null', () => {
    expect(
      render([
        ['a', atom('selector')],
        ['b', atom('Like This')],
      ]),
    ).toContain("        a => selector,\n        b => 'Like This'\n    };");
    expect(
      render([
        ['n', 42],
        ['f', 1.5],
        ['big', 1e21],
        ['small', 1e-7],
      ]),
    ).toContain(
      '        n => 42,\n        f => 1.5,\n        big => 1000000000000000000000,\n        small => 1.0e-7\n    };',
    );
    expect(
      render([
        ['t', true],
        ['f', false],
        ['z', null],
      ]),
    ).toContain('        t => true,\n        f => false,\n        z => undefined\n    };');
  });

  it('writes strings as utf8 binaries and lists without spaces', () => {
    expect(
      render([
        ['s', 'say "hi"'],
        ['l', [1, 'x', atom('y')]],
        ['e', []],
      ]),
    ).toContain(
      '        s => <<"say \\"hi\\""/utf8>>,\n        l => [1,<<"x"/utf8>>,y],\n        e => []\n    };',
    );
  });

  it('writes nested maps inline and an empty top-level map in the reference layout', () => {
    expect(
      render([
        [
          'inline',
          [
            {
              map: [
                ['k', 1],
                ['Q', atom('v')],
              ],
            },
          ],
        ],
        ['empty', { map: [] }],
      ]),
    ).toContain("        inline => [#{k => 1, 'Q' => v}],\n        empty => #{\n        }\n    };");
  });

  it('writes a non-empty top-level map on indented lines', () => {
    expect(
      render([
        [
          'properties',
          {
            map: [
              ['sight_dist', 5000],
              ['trace_dist', 5000],
            ],
          },
        ],
      ]),
    ).toContain(
      '        properties => #{\n            sight_dist => 5000,\n            trace_dist => 5000\n        }\n    };',
    );
  });

  it('writes the entry comment before its clause', () => {
    const erl = toErlang(modelWith([], 'Selector - Root'), { module: 'm', sourcePath: 's' });
    expect(erl).toContain('%% Selector - Root\nget_node(1) ->');
  });
});
