import {
  isExportAtom,
  isExportMap,
  type ExportEntry,
  type ExportMap,
  type ExportModel,
  type ExportValue,
} from './model';
import { erlangAtom, erlangString } from './names';

export interface ErlangOptions {
  /** Erlang module name (already sanitized). */
  module: string;
  /** Tree file path relative to the project directory, forward slashes. */
  sourcePath: string;
}

const CLAUSE_INDENT = 4;
const FIELD_INDENT = 8;

/** Integers print without a decimal point; other numbers always contain one (`1.0e+21`). */
function erlangNumber(n: number): string {
  if (Number.isInteger(n)) {
    return /e/.test(String(n)) ? BigInt(n).toString() : String(n);
  }
  const text = String(n);
  return text.includes('.') ? text : text.replace('e', '.0e');
}

/** Single-line Erlang term. */
function inline(value: ExportValue): string {
  if (value === null) {
    return 'undefined';
  }
  if (typeof value === 'boolean') {
    return value ? 'true' : 'false';
  }
  if (typeof value === 'number') {
    return erlangNumber(value);
  }
  if (typeof value === 'string') {
    return erlangString(value);
  }
  if (Array.isArray(value)) {
    return `[${value.map((item) => inline(item)).join(',')}]`;
  }
  if (isExportAtom(value)) {
    return erlangAtom(value.atom);
  }
  return `#{${value.map.map(([key, inner]) => `${erlangAtom(key)} => ${inline(inner)}`).join(', ')}}`;
}

/** Multi-line map for the top level of a clause. Empty maps keep the `#{` newline `}` layout. */
function multilineMap(map: ExportMap, indent: number): string {
  const closing = `${' '.repeat(indent)}}`;
  if (map.map.length === 0) {
    return `#{\n${closing}`;
  }
  const inner = ' '.repeat(indent + 4);
  const lines = map.map.map(([key, value]) => `${inner}${erlangAtom(key)} => ${inline(value)}`);
  return `#{\n${lines.join(',\n')}\n${closing}`;
}

function topLevel(value: ExportValue): string {
  return isExportMap(value) ? multilineMap(value, FIELD_INDENT) : inline(value);
}

function clause(entry: ExportEntry): string[] {
  const fields = entry.fields.map(
    ([key, value]) => `${' '.repeat(FIELD_INDENT)}${erlangAtom(key)} => ${topLevel(value)}`,
  );
  return [
    `%% ${entry.comment}`,
    `get_node(${entry.id}) ->`,
    `${' '.repeat(CLAUSE_INDENT)}#{`,
    fields.join(',\n'),
    `${' '.repeat(CLAUSE_INDENT)}};`,
  ];
}

/** Renders the export model as an Erlang module with get_node/1 and get_root_node/0. */
export function toErlang(model: ExportModel, options: ErlangOptions): string {
  const rule = `%%${'-'.repeat(78)}`;
  const lines: string[] = [
    '%% -*- coding: utf-8 -*-',
    rule,
    `%% @File   : ${options.module}`,
    `%% @Generated by owl-bt from ${options.sourcePath}. Do not edit.`,
    rule,
    `-module(${options.module}).`,
    '-export([',
    '    get_node/1,',
    '    get_root_node/0',
    ']).',
    '',
    '',
  ];
  for (const entry of model.entries) {
    lines.push(...clause(entry));
  }
  // The reference file ends with two blank lines after the root accessor.
  lines.push(
    'get_node(_) -> undefined.',
    '',
    '',
    `get_root_node() -> ${model.rootId}.`,
    '',
    '',
    '',
  );
  return lines.join('\n');
}
