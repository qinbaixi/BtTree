import { describe, expect, it } from 'vitest';
import { toGo } from './go';
import { atom, type ExportModel, type ExportValue } from './model';

const OPTIONS = { sourcePath: 'trees/x.json', packageName: 'behaviortrees', namePrefix: 'BtX' };

function modelWith(fields: Array<[string, ExportValue]>, comment = 'Thing'): ExportModel {
  return {
    rootId: 1,
    entries: [{ id: 1, kind: 'node', comment, fields: [['node_id', 1], ...fields] }],
    warnings: [],
  };
}

function render(fields: Array<[string, ExportValue]>, comment?: string): string {
  return toGo(modelWith(fields, comment), OPTIONS);
}

/** The value of the `"a"` element of the single test entry. */
function fieldValue(value: ExportValue): string {
  const go = render([['a', value]]);
  const line = go.split('\n').find((text) => text.startsWith('\t\t"a": '));
  if (line === undefined) {
    throw new Error('field line not found');
  }
  return line.slice('\t\t"a": '.length).trimStart();
}

describe('toGo', () => {
  it('writes the header, package, RootID, Nodes and GetNode', () => {
    expect(toGo(modelWith([]), OPTIONS)).toBe(
      [
        '// Code generated by owl-bt from trees/x.json. DO NOT EDIT.',
        '',
        'package behaviortrees',
        '',
        '// BtXRootID is the id of the root node.',
        'const BtXRootID = 1',
        '',
        '// BtXNodes holds every node, decorator and service by id.',
        'var BtXNodes = map[int]map[string]any{',
        '\t// Thing',
        '\t1: {',
        '\t\t"node_id": 1,',
        '\t},',
        '}',
        '',
        '// BtXGetNode returns the item with the given id, or nil when there is none.',
        'func BtXGetNode(id int) map[string]any {',
        '\treturn BtXNodes[id]',
        '}',
        '',
      ].join('\n'),
    );
  });

  it('uses the given package and name prefix', () => {
    const go = toGo(modelWith([]), { ...OPTIONS, packageName: 'ai', namePrefix: 'Mon' });
    expect(go).toContain('package ai\n');
    expect(go).toContain('const MonRootID = 1\n');
    expect(go).toContain('func MonGetNode(id int) map[string]any {\n\treturn MonNodes[id]\n}');
  });

  it('writes int literals for int32 values and int64 conversions beyond', () => {
    expect(fieldValue(2147483647)).toBe('2147483647,');
    expect(fieldValue(-2147483648)).toBe('-2147483648,');
    expect(fieldValue(2147483648)).toBe('int64(2147483648),');
    expect(fieldValue(2 ** 62)).toBe('int64(4611686018427387904),');
  });

  it('writes other numbers as float64 constants with a decimal point or exponent', () => {
    expect(fieldValue(0.5)).toBe('0.5,');
    expect(fieldValue(-2.25)).toBe('-2.25,');
    expect(fieldValue(1.5e21)).toBe('1.5e+21,');
    expect(fieldValue(1e-7)).toBe('1e-7,');
    expect(fieldValue(2 ** 63)).toBe('9223372036854776000.0,');
  });

  it('imports math only for NaN and infinities', () => {
    expect(render([['a', 1]])).not.toContain('import');
    const go = render([
      ['a', Infinity],
      ['b', -Infinity],
      ['c', NaN],
    ]);
    expect(go).toContain('package behaviortrees\n\nimport "math"\n\n// BtXRootID');
    expect(go).toContain('\t\t"a":       math.Inf(1),\n\t\t"b":       math.Inf(-1),\n');
    expect(go).toContain('\t\t"c":       math.NaN(),\n');
  });

  it('writes booleans and nil as literals', () => {
    expect(fieldValue(true)).toBe('true,');
    expect(fieldValue(false)).toBe('false,');
    expect(fieldValue(null)).toBe('nil,');
  });

  it('writes strings and atoms as escaped string literals', () => {
    expect(fieldValue(atom('selector'))).toBe('"selector",');
    expect(fieldValue('say "hi" \\ ok')).toBe('"say \\"hi\\" \\\\ ok",');
    expect(fieldValue('a\nb\rc\td\u0001\u007f')).toBe('"a\\nb\\rc\\td\\x01\\x7f",');
    expect(fieldValue('中文')).toBe('"中文",');
    expect(fieldValue('﻿\ud800')).toBe('"\\uFEFF\\uFFFD",');
  });

  it('writes id lists as int slices, other arrays as any slices', () => {
    const go = render([
      ['children', [3, 5]],
      ['mixed', [1, 'x', atom('y'), null]],
      ['empty', []],
      ['decorators', []],
    ]);
    expect(go).toContain('\t\t"children":   []int{3, 5},\n');
    expect(go).toContain('\t\t"mixed":      []any{1, "x", "y", nil},\n');
    expect(go).toContain('\t\t"empty":      []any{},\n');
    expect(go).toContain('\t\t"decorators": []int{},\n');
  });

  it('writes a non-empty top-level map one key per line, aligned like gofmt', () => {
    const go = render([
      ['type', atom('task')],
      [
        'properties',
        {
          map: [
            ['sight_dist', 5000],
            ['x', 'y'],
          ],
        },
      ],
      ['after', 1],
    ]);
    expect(go).toContain(
      [
        '\t\t"node_id": 1,',
        '\t\t"type":    "task",',
        '\t\t"properties": map[string]any{',
        '\t\t\t"sight_dist": 5000,',
        '\t\t\t"x":          "y",',
        '\t\t},',
        '\t\t"after": 1,',
      ].join('\n'),
    );
  });

  it('does not pad a single-element map', () => {
    expect(render([['properties', { map: [['k', 1]] }]])).toContain(
      '\t\t"properties": map[string]any{\n\t\t\t"k": 1,\n\t\t},',
    );
  });

  it('writes an empty top-level map and nested maps inline', () => {
    expect(fieldValue({ map: [] })).toBe('map[string]any{},');
    expect(
      fieldValue([
        {
          map: [
            ['k', 1],
            ['with "quote"', null],
          ],
        },
      ]),
    ).toBe('[]any{map[string]any{"k": 1, "with \\"quote\\"": nil}},');
  });

  it('starts a new alignment run for a long key far from the average size', () => {
    const long = 'k'.repeat(120);
    const go = render([
      ['a', 1],
      ['b', 2],
      [long, 3],
    ]);
    expect(go).toContain(
      `\t\t"node_id": 1,\n\t\t"a":       1,\n\t\t"b":       2,\n\t\t"${long}": 3,\n`,
    );
  });

  it('writes one comment line per entry and keeps line breaks out of it', () => {
    const go = render([], 'Selector - Root\r\nNext line ');
    expect(go).toContain('\t// Selector - Root Next line\n\t1: {');
  });

  it('renders very large trees without hitting argument-count limits', () => {
    const count = 60000;
    const model: ExportModel = {
      rootId: 1,
      entries: Array.from({ length: count }, (_, i) => ({
        id: i + 1,
        kind: 'node' as const,
        comment: 'Task',
        fields: [['node_id', i + 1]] as Array<[string, ExportValue]>,
      })),
      warnings: [],
    };
    const go = toGo(model, OPTIONS);
    expect(go).toContain(`\t${count}: {\n\t\t"node_id": ${count},\n\t},\n}\n`);
  });
});
