import { describe, expect, it } from 'vitest';
import { toLua } from './lua';
import { atom, type ExportModel, type ExportValue } from './model';

function modelWith(fields: Array<[string, ExportValue]>, comment = 'Thing'): ExportModel {
  return {
    rootId: 1,
    entries: [{ id: 1, kind: 'node', comment, fields: [['node_id', 1], ...fields] }],
    warnings: [],
  };
}

function render(fields: Array<[string, ExportValue]>, comment?: string): string {
  return toLua(modelWith(fields, comment), { sourcePath: 'trees/x.json' });
}

describe('toLua', () => {
  it('wraps the entries in nodes and returns root, nodes and get_node', () => {
    const lua = toLua(modelWith([]), { sourcePath: 'trees/x.json' });
    expect(lua).toBe(
      [
        '-- Generated by owl-bt from trees/x.json. Do not edit.',
        'local nodes = {',
        '    -- Thing',
        '    [1] = {',
        '        node_id = 1,',
        '    },',
        '}',
        '',
        'return {',
        '    root = 1,',
        '    nodes = nodes,',
        '    get_node = function(id) return nodes[id] end,',
        '}',
        '',
      ].join('\n'),
    );
  });

  it('writes atoms as strings, null as nil and booleans and numbers as literals', () => {
    expect(
      render([
        ['a', atom('selector')],
        ['n', null],
        ['t', true],
        ['x', 2.5],
      ]),
    ).toContain('        a = "selector",\n        n = nil,\n        t = true,\n        x = 2.5,');
  });

  it('writes lists with spaces and empty tables as {}', () => {
    expect(
      render([
        ['l', [1, 'a']],
        ['e', []],
        ['m', { map: [] }],
      ]),
    ).toContain('        l = {1, "a"},\n        e = {},\n        m = {},');
  });

  it('writes nested maps inline with bracketed keys when needed', () => {
    expect(
      render([
        [
          'm',
          [
            {
              map: [
                ['k', 1],
                ['with space', 'v'],
                ['end', false],
              ],
            },
          ],
        ],
      ]),
    ).toContain('        m = {{ k = 1, ["with space"] = "v", ["end"] = false }},');
  });

  it('writes a non-empty top-level map one key per line', () => {
    expect(
      render([
        [
          'properties',
          {
            map: [
              ['sight_dist', 5000],
              ['trace_dist', 5000],
            ],
          },
        ],
      ]),
    ).toContain(
      '        properties = {\n            sight_dist = 5000,\n            trace_dist = 5000,\n        },',
    );
  });

  it('writes the entry comment above its table', () => {
    expect(render([], 'Selector - Root')).toContain('    -- Selector - Root\n    [1] = {');
  });
});
