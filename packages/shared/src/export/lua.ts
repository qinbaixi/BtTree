import {
  cachedFormatter,
  isExportAtom,
  isExportMap,
  type ExportEntry,
  type ExportMap,
  type ExportModel,
  type ExportValue,
} from './model';
import { luaKey as formatLuaKey, luaString } from './names';

export interface LuaOptions {
  /** Tree file path relative to the project directory, forward slashes. */
  sourcePath: string;
}

const ENTRY_INDENT = 4;
const FIELD_INDENT = 8;
const ENTRY_PAD = ' '.repeat(ENTRY_INDENT);
const FIELD_PAD = ' '.repeat(FIELD_INDENT);

const luaKey = cachedFormatter(formatLuaKey);

/** Single-line Lua expression. Atoms become strings, maps become tables. */
function inline(value: ExportValue): string {
  if (value === null) {
    return 'nil';
  }
  if (typeof value === 'boolean' || typeof value === 'number') {
    return String(value);
  }
  if (typeof value === 'string') {
    return luaString(value);
  }
  if (Array.isArray(value)) {
    return `{${value.map((item) => inline(item)).join(', ')}}`;
  }
  if (isExportAtom(value)) {
    return luaString(value.atom);
  }
  if (value.map.length === 0) {
    return '{}';
  }
  return `{ ${value.map.map(([key, inner]) => `${luaKey(key)} = ${inline(inner)}`).join(', ')} }`;
}

/** Table for the top level of an entry, one key per line. Empty tables stay `{}`. */
function multilineTable(map: ExportMap, indent: number): string {
  if (map.map.length === 0) {
    return '{}';
  }
  const inner = ' '.repeat(indent + 4);
  const lines = map.map.map(([key, value]) => `${inner}${luaKey(key)} = ${inline(value)},`);
  return `{\n${lines.join('\n')}\n${' '.repeat(indent)}}`;
}

function topLevel(value: ExportValue): string {
  return isExportMap(value) ? multilineTable(value, FIELD_INDENT) : inline(value);
}

function pushEntryLines(lines: string[], entry: ExportEntry): void {
  lines.push(`${ENTRY_PAD}-- ${entry.comment}`, `${ENTRY_PAD}[${entry.id}] = {`);
  for (const [key, value] of entry.fields) {
    lines.push(`${FIELD_PAD}${luaKey(key)} = ${topLevel(value)},`);
  }
  lines.push(`${ENTRY_PAD}},`);
}

/** Renders the export model as a Lua module returning { root, nodes, get_node }. */
export function toLua(model: ExportModel, options: LuaOptions): string {
  const lines: string[] = [
    `-- Generated by owl-bt from ${options.sourcePath}. Do not edit.`,
    'local nodes = {',
  ];
  for (const entry of model.entries) {
    pushEntryLines(lines, entry);
  }
  lines.push(
    '}',
    '',
    'return {',
    `    root = ${model.rootId},`,
    '    nodes = nodes,',
    '    get_node = function(id) return nodes[id] end,',
    '}',
    '',
  );
  return lines.join('\n');
}
