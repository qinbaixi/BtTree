import { describe, expect, it } from 'vitest';
import { compileProject } from '../compileProject';
import type { SubtreeLibrary } from '../subtree';
import { createIdGen, nodeFromJson } from '../treeModel';
import {
  buildExportModel,
  ExportError,
  toCSharp,
  toErlang,
  toGo,
  toLua,
  toTypeScript,
} from './index';

/** Golden exports of a tree with a subtree reference, in 'reference' and 'inline' mode. */
const project = compileProject({
  nodes: [
    { name: 'Sequence', isComposite: true },
    { name: 'Attack', properties: [{ name: 'Range', type: 'number', default: 2 }] },
    { name: 'Patrol' },
    { name: 'SubTree', subtree: true },
  ],
  decorators: [{ name: 'Guard' }],
});

const tree = () =>
  nodeFromJson(
    {
      type: 'Sequence',
      label: 'Main',
      childNodes: [
        {
          type: 'SubTree',
          label: 'Common',
          decorators: [{ type: 'Guard' }],
          properties: [{ name: 'Tree', value: 'trees/common/patrol.json' }],
        },
        { type: 'Attack' },
      ],
    },
    createIdGen(),
  );

const library: SubtreeLibrary = {
  'trees/common/patrol.json': { tree: { type: 'Sequence', childNodes: [{ type: 'Patrol' }] } },
};

type Mode = 'reference' | 'inline';

function render(mode: Mode) {
  const model = buildExportModel(tree(), project, {
    subtrees: mode,
    library,
    treeRef: 'trees/main.json',
  });
  const sourcePath = 'trees/main.json';
  return {
    lua: toLua(model, { sourcePath }),
    erl: toErlang(model, { module: 'main', sourcePath }),
    ts: toTypeScript(model, { sourcePath }),
    cs: toCSharp(model, { sourcePath, className: 'Main', namespace: 'BehaviorTrees' }),
    go: toGo(model, { sourcePath, packageName: 'behaviortrees', namePrefix: 'Main' }),
  };
}

