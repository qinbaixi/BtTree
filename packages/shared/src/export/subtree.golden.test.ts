describe('golden export of subtree references', () => {
  for (const mode of ['reference', 'inline'] as const) {
    for (const format of ['lua', 'erl', 'ts', 'cs', 'go'] as const) {
      it(`writes ${format} in ${mode} mode`, () => {
        expect(render(mode)[format]).toBe(EXPECTED[mode][format]);
      });
    }
  }

  it('defaults to reference mode', () => {
    const model = buildExportModel(tree(), project);
    expect(toLua(model, { sourcePath: 'trees/main.json' })).toBe(EXPECTED.reference.lua);
  });

  it('warns about unusable references in reference mode', () => {
    const root = nodeFromJson(
      {
        type: 'Sequence',
        childNodes: [
          { type: 'SubTree', properties: [{ name: 'Tree', value: 'trees/none.json' }] },
          { type: 'SubTree', properties: [{ name: 'Tree', value: 'trees/main.json' }] },
        ],
      },
      createIdGen(),
    );
    const model = buildExportModel(root, project, {
      library: {
        'trees/none.json': {
          error: 'missing',
          message: "Referenced tree 'trees/none.json' not found",
        },
      },
      treeRef: 'trees/main.json',
    });
    expect(model.warnings).toEqual([
      "root.childNodes[0]: Referenced tree 'trees/none.json' not found",
      'root.childNodes[1]: Subtree cycle: trees/main.json → trees/main.json',
    ]);
  });

  it('refuses to inline missing trees and cycles', () => {
    const cyclic: SubtreeLibrary = {
      'trees/a.json': {
        tree: { type: 'SubTree', properties: [{ name: 'Tree', value: 'trees/main.json' }] },
      },
    };
    const root = nodeFromJson(
      { type: 'SubTree', properties: [{ name: 'Tree', value: 'trees/a.json' }] },
      createIdGen(),
    );
    expect(() =>
      buildExportModel(root, project, {
        subtrees: 'inline',
        library: cyclic,
        treeRef: 'trees/main.json',
      }),
    ).toThrow(
      new ExportError(
        'Cannot inline subtree at a nested subtree (trees/a.json): Subtree cycle: trees/main.json → trees/a.json → trees/main.json',
      ),
    );
    expect(() => buildExportModel(root, project, { subtrees: 'inline', library: {} })).toThrow(
      "Cannot inline subtree at root: Referenced tree 'trees/a.json' is not loaded",
    );
  });
});
