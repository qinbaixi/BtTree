import { describe, expect, it } from 'vitest';
import { atom, type ExportModel, type ExportValue } from './model';
import { toTypeScript } from './typescript';

function modelWith(fields: Array<[string, ExportValue]>, comment = 'Thing'): ExportModel {
  return {
    rootId: 1,
    entries: [{ id: 1, kind: 'node', comment, fields: [['node_id', 1], ...fields] }],
    warnings: [],
  };
}

function render(fields: Array<[string, ExportValue]>, comment?: string): string {
  return toTypeScript(modelWith(fields, comment), { sourcePath: 'trees/x.json' });
}

describe('toTypeScript', () => {
  it('writes the header, the BtNode interface, rootId, nodes and getNode', () => {
    const ts = toTypeScript(modelWith([]), { sourcePath: 'trees/x.json' });
    expect(ts).toBe(
      [
        '// Generated by owl-bt from trees/x.json. Do not edit.',
        'export interface BtNode {',
        '  node_id: number;',
        '  type: string;',
        '  sub_type: string | number;',
        '  [key: string]: unknown;',
        '}',
        '',
        'export const rootId = 1;',
        '',
        'export const nodes: Readonly<Record<number, BtNode>> = {',
        '  // Thing',
        '  1: {',
        '    node_id: 1,',
        '  },',
        '};',
        '',
        'export function getNode(id: number): BtNode | undefined {',
        '  return nodes[id];',
        '}',
        '',
      ].join('\n'),
    );
  });

  it('writes atoms as single-quoted strings and strings with escapes', () => {
    expect(render([['a', atom('selector')]])).toContain("    a: 'selector',\n");
    expect(render([['s', "it's a \\ b\n\r\t\u0001\u007f"]])).toContain(
      "    s: 'it\\'s a \\\\ b\\n\\r\\t\\u0001\\u007f',\n",
    );
  });

  it('escapes the comment line so a label cannot end the comment', () => {
    expect(render([], 'Selector - Root\nNext line')).toContain(
      '  // Selector - Root Next line\n  1: {',
    );
  });

  it('writes numbers as they are, booleans and null as literals', () => {
    expect(
      render([
        ['i', 42],
        ['neg', -7],
        ['x', 2.5],
        ['big', 1e21],
        ['t', true],
        ['f', false],
        ['n', null],
      ]),
    ).toContain(
      '    i: 42,\n    neg: -7,\n    x: 2.5,\n    big: 1e+21,\n    t: true,\n    f: false,\n    n: null,\n',
    );
  });

  it('writes lists inline and empty lists as []', () => {
    expect(
      render([
        ['l', [1, 'a', atom('b')]],
        ['e', []],
      ]),
    ).toContain("    l: [1, 'a', 'b'],\n    e: [],\n");
  });

  it('writes nested maps inline and quotes keys that are not identifiers', () => {
    expect(
      render([
        [
          'm',
          [
            {
              map: [
                ['k', 1],
                ['with space', 'v'],
                ['end', false],
                ["it's", null],
              ],
            },
          ],
        ],
        ['empty', { map: [] }],
      ]),
    ).toContain(
      "    m: [{ k: 1, 'with space': 'v', end: false, 'it\\'s': null }],\n    empty: {},\n",
    );
  });

  it('writes a non-empty top-level map one key per line with a trailing comma', () => {
    expect(
      render([
        [
          'properties',
          {
            map: [
              ['sight_dist', 5000],
              ['trace_dist', 5000],
            ],
          },
        ],
        ['none', { map: [] }],
      ]),
    ).toContain(
      '    properties: {\n      sight_dist: 5000,\n      trace_dist: 5000,\n    },\n    none: {},\n',
    );
  });

  it('writes one entry per numbered item with its comment above it', () => {
    const model: ExportModel = {
      rootId: 1,
      entries: [
        { id: 1, kind: 'node', comment: 'Selector - Root', fields: [['node_id', 1]] },
        { id: 2, kind: 'decorator', comment: 'Decorator21', fields: [['node_id', 2]] },
      ],
      warnings: [],
    };
    const ts = toTypeScript(model, { sourcePath: 'trees/x.json' });
    expect(ts).toContain(
      '  // Selector - Root\n  1: {\n    node_id: 1,\n  },\n  // Decorator21\n  2: {\n    node_id: 2,\n  },\n};',
    );
  });
});
