import {
  cachedFormatter,
  isExportAtom,
  isExportMap,
  type ExportEntry,
  type ExportMap,
  type ExportModel,
  type ExportValue,
} from './model';
import { tsKey as formatTsKey, tsString } from './names';

export interface TypeScriptOptions {
  /** Tree file path relative to the project directory, forward slashes. */
  sourcePath: string;
}

const ENTRY_INDENT = 2;
const FIELD_INDENT = 4;
const ENTRY_PAD = ' '.repeat(ENTRY_INDENT);
const FIELD_PAD = ' '.repeat(FIELD_INDENT);

const tsKey = cachedFormatter(formatTsKey);

/** Single-line TypeScript expression. Atoms become strings, maps become object literals. */
function inline(value: ExportValue): string {
  if (value === null) {
    return 'null';
  }
  if (typeof value === 'boolean' || typeof value === 'number') {
    return String(value);
  }
  if (typeof value === 'string') {
    return tsString(value);
  }
  if (Array.isArray(value)) {
    return `[${value.map((item) => inline(item)).join(', ')}]`;
  }
  if (isExportAtom(value)) {
    return tsString(value.atom);
  }
  if (value.map.length === 0) {
    return '{}';
  }
  return `{ ${value.map.map(([key, inner]) => `${tsKey(key)}: ${inline(inner)}`).join(', ')} }`;
}

/** Object literal for the top level of an entry, one key per line. Empty objects stay `{}`. */
function multilineObject(map: ExportMap, indent: number): string {
  if (map.map.length === 0) {
    return '{}';
  }
  const inner = ' '.repeat(indent + 2);
  const lines = map.map.map(([key, value]) => `${inner}${tsKey(key)}: ${inline(value)},`);
  return `{\n${lines.join('\n')}\n${' '.repeat(indent)}}`;
}

function topLevel(value: ExportValue): string {
  return isExportMap(value) ? multilineObject(value, FIELD_INDENT) : inline(value);
}

/** Line terminators in comments: CR, LF, U+2028 and U+2029. */
const LINE_BREAKS = new RegExp('[\\r\\n\\u2028\\u2029]+', 'g');

/** Comment text on one line. */
function lineComment(text: string): string {
  return text.replace(LINE_BREAKS, ' ');
}

function pushEntryLines(lines: string[], entry: ExportEntry): void {
  lines.push(`${ENTRY_PAD}// ${lineComment(entry.comment)}`, `${ENTRY_PAD}${entry.id}: {`);
  for (const [key, value] of entry.fields) {
    lines.push(`${FIELD_PAD}${tsKey(key)}: ${topLevel(value)},`);
  }
  lines.push(`${ENTRY_PAD}},`);
}

/** Renders the export model as a TypeScript module with rootId, nodes and getNode(). */
export function toTypeScript(model: ExportModel, options: TypeScriptOptions): string {
  const lines: string[] = [
    `// Generated by owl-bt from ${options.sourcePath}. Do not edit.`,
    'export interface BtNode {',
    '  node_id: number;',
    '  type: string;',
    '  sub_type: string | number;',
    '  [key: string]: unknown;',
    '}',
    '',
    `export const rootId = ${model.rootId};`,
    '',
    'export const nodes: Readonly<Record<number, BtNode>> = {',
  ];
  for (const entry of model.entries) {
    pushEntryLines(lines, entry);
  }
  lines.push(
    '};',
    '',
    'export function getNode(id: number): BtNode | undefined {',
    '  return nodes[id];',
    '}',
    '',
  );
  return lines.join('\n');
}
